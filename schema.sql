CREATE DATABASE QuanLyNgoaiHangAnh
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE QuanLyNgoaiHangAnh;
-- 1. CAU_THU
CREATE TABLE CauThu (
    MaCT VARCHAR(10) PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    NgaySinh DATE,
    QuocTich VARCHAR(50),
    ViTri ENUM('Thủ môn', 'Hậu vệ', 'Tiền vệ', 'Tiền đạo') NOT NULL
) ENGINE=InnoDB;


-- 2. CAU_LAC_BO
CREATE TABLE CauLacBo (
    MaCLB VARCHAR(10) PRIMARY KEY,
    TenCLB VARCHAR(100) NOT NULL UNIQUE,
    SanNha VARCHAR(100),
    ThanhPho VARCHAR(50),
    NamThanhLap SMALLINT UNSIGNED
) ENGINE=InnoDB;


-- 3. HOP_DONG
CREATE TABLE HopDong (
    MaHD VARCHAR(10) PRIMARY KEY,
    MaCT VARCHAR(10) NOT NULL,
    MaCLB VARCHAR(10) NOT NULL,
    NgayKy DATE NOT NULL,
    NgayKetThuc DATE NOT NULL,

    CONSTRAINT FK_HD_CauThu
        FOREIGN KEY (MaCT) REFERENCES CauThu(MaCT)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT FK_HD_CLB
        FOREIGN KEY (MaCLB) REFERENCES CauLacBo(MaCLB)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT CK_HD_ThoiGian
        CHECK (NgayKy < NgayKetThuc),

    INDEX IDX_HD_MaCT (MaCT),
    INDEX IDX_HD_MaCLB (MaCLB)
) ENGINE=InnoDB;


-- 4. HUAN_LUYEN_VIEN
CREATE TABLE HuanLuyenVien (
    MaHLV VARCHAR(10) PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    QuocTich VARCHAR(50)
) ENGINE=InnoDB;


-- 5. BO_NHIEM_HLV
CREATE TABLE BoNhiemHLV (
    MaBoNhiem VARCHAR(10) PRIMARY KEY,
    MaHLV VARCHAR(10) NOT NULL,
    MaCLB VARCHAR(10) NOT NULL,
    NgayBoNhiem DATE NOT NULL,
    NgayKetThuc DATE NULL,

    CONSTRAINT FK_BN_HLV
        FOREIGN KEY (MaHLV) REFERENCES HuanLuyenVien(MaHLV)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT FK_BN_CLB
        FOREIGN KEY (MaCLB) REFERENCES CauLacBo(MaCLB)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT CK_BN_ThoiGian
        CHECK (NgayKetThuc IS NULL OR NgayBoNhiem < NgayKetThuc),

    INDEX IDX_BN_MaHLV (MaHLV),
    INDEX IDX_BN_MaCLB (MaCLB)
) ENGINE=InnoDB;


-- 6. MUA_GIAI
CREATE TABLE MuaGiai (
    MaMuaGiai VARCHAR(10) PRIMARY KEY,
    TenMuaGiai VARCHAR(20) NOT NULL UNIQUE,
    ThoiGianBatDau DATE NOT NULL,
    ThoiGianKetThuc DATE NOT NULL,

    CONSTRAINT CK_MG_ThoiGian
        CHECK (ThoiGianBatDau < ThoiGianKetThuc)
) ENGINE=InnoDB;


-- 7. TRAN_DAU
CREATE TABLE TranDau (
    MaTD VARCHAR(10) PRIMARY KEY,
    MaMuaGiai VARCHAR(10) NOT NULL,
    MaCLBNha VARCHAR(10) NOT NULL,
    MaCLBKhach VARCHAR(10) NOT NULL,
    VongDau TINYINT UNSIGNED NOT NULL,
    ThoiGianThiDau DATETIME NOT NULL,
    SanVanDong VARCHAR(100),
    TiSoNha TINYINT UNSIGNED NULL,
    TiSoKhach TINYINT UNSIGNED NULL,

    CONSTRAINT FK_TD_MuaGiai
        FOREIGN KEY (MaMuaGiai) REFERENCES MuaGiai(MaMuaGiai)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT FK_TD_CLBNha
        FOREIGN KEY (MaCLBNha) REFERENCES CauLacBo(MaCLB)
        ON DELETE RESTRICT ON UPDATE RESTRICT,

    CONSTRAINT FK_TD_CLBKhach
        FOREIGN KEY (MaCLBKhach) REFERENCES CauLacBo(MaCLB)
        ON DELETE RESTRICT ON UPDATE RESTRICT,

    CONSTRAINT CK_TD_KhacCLB
        CHECK (MaCLBNha <> MaCLBKhach),

    INDEX IDX_TD_MuaGiai (MaMuaGiai),
    INDEX IDX_TD_CLBNha (MaCLBNha),
    INDEX IDX_TD_CLBKhach (MaCLBKhach),
    INDEX IDX_TD_ThoiGian (ThoiGianThiDau)
) ENGINE=InnoDB;


-- 8. BAN_THANG
CREATE TABLE BanThang (
    MaBT VARCHAR(10) PRIMARY KEY,
    MaTD VARCHAR(10) NOT NULL,
    MaHD VARCHAR(10) NOT NULL,
    PhutGhiBan SMALLINT UNSIGNED NOT NULL,
    LoaiBanThang ENUM('Thường', 'Penalty', 'Phản lưới nhà') NOT NULL,
    MaHDKienTao VARCHAR(10) NULL,

    CONSTRAINT FK_BT_TranDau
        FOREIGN KEY (MaTD) REFERENCES TranDau(MaTD)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT FK_BT_HopDong
        FOREIGN KEY (MaHD) REFERENCES HopDong(MaHD)
        ON DELETE RESTRICT ON UPDATE RESTRICT,

    CONSTRAINT FK_BT_KienTao
        FOREIGN KEY (MaHDKienTao) REFERENCES HopDong(MaHD)
        ON DELETE RESTRICT ON UPDATE RESTRICT,

    CONSTRAINT CK_BT_KienTao
        CHECK (MaHDKienTao IS NULL OR MaHDKienTao <> MaHD),

    INDEX IDX_BT_MaTD (MaTD),
    INDEX IDX_BT_MaHD (MaHD)
) ENGINE=InnoDB;


-- 9. THE_PHAT
CREATE TABLE ThePhat (
    MaThe VARCHAR(10) PRIMARY KEY,
    MaTD VARCHAR(10) NOT NULL,
    MaHD VARCHAR(10) NOT NULL,
    PhutNhanThe SMALLINT UNSIGNED NOT NULL,
    LoaiThe ENUM('Vàng', 'Đỏ') NOT NULL,

    CONSTRAINT FK_TP_TranDau
        FOREIGN KEY (MaTD) REFERENCES TranDau(MaTD)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT FK_TP_HopDong
        FOREIGN KEY (MaHD) REFERENCES HopDong(MaHD)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    INDEX IDX_TP_MaTD (MaTD),
    INDEX IDX_TP_MaHD (MaHD)
) ENGINE=InnoDB;


-- 10. THONG_KE_PHONG_DO
CREATE TABLE ThongKePhongDo (
    MaThongKe VARCHAR(10) PRIMARY KEY,
    MaCLB VARCHAR(10) NOT NULL,
    MaTD VARCHAR(10) NOT NULL,
    SoTranThang5TranGanNhat TINYINT UNSIGNED NOT NULL,
    TrungBinhBanThang DECIMAL(5,2) NOT NULL,
    TrungBinhBanThua DECIMAL(5,2) NOT NULL,
    SoNgayNghi SMALLINT UNSIGNED NOT NULL,
    ThoiDiemTinh DATETIME NOT NULL,

    CONSTRAINT FK_TK_CLB
        FOREIGN KEY (MaCLB) REFERENCES CauLacBo(MaCLB)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT FK_TK_TranDau
        FOREIGN KEY (MaTD) REFERENCES TranDau(MaTD)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT CK_TK_SoTranThang
        CHECK (SoTranThang5TranGanNhat BETWEEN 0 AND 5),

    CONSTRAINT CK_TK_TrungBinh
        CHECK (TrungBinhBanThang >= 0 AND TrungBinhBanThua >= 0),

    CONSTRAINT UQ_TK_CLB_TranDau
        UNIQUE (MaCLB, MaTD),

    INDEX IDX_TK_MaTD (MaTD)
) ENGINE=InnoDB;


-- 11. DU_DOAN_TRAN_DAU
CREATE TABLE DuDoanTranDau (
    MaDuDoan VARCHAR(10) PRIMARY KEY,
    MaTD VARCHAR(10) NOT NULL,
    XacSuatThangNha DECIMAL(5,2) NOT NULL,
    XacSuatHoa DECIMAL(5,2) NOT NULL,
    XacSuatThangKhach DECIMAL(5,2) NOT NULL,
    NgayGioChayDuDoan DATETIME NOT NULL,
    KetQuaThucTe ENUM('Thắng nhà', 'Hòa', 'Thắng khách') NULL,

    CONSTRAINT FK_DD_TranDau
        FOREIGN KEY (MaTD) REFERENCES TranDau(MaTD)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT CK_DD_XacSuat
        CHECK (
            XacSuatThangNha BETWEEN 0 AND 100
            AND XacSuatHoa BETWEEN 0 AND 100
            AND XacSuatThangKhach BETWEEN 0 AND 100
            AND XacSuatThangNha
                + XacSuatHoa
                + XacSuatThangKhach = 100
        ),

    INDEX IDX_DD_MaTD (MaTD),
    INDEX IDX_DD_NgayGio (NgayGioChayDuDoan)
) ENGINE=InnoDB;
